# Pause is inserted AFTER each of these word indices (0-based, in the aligned word list).
PAUSE_AFTER = [2, 8, 13, 16, 21, 30, 34, 46, 54, 62, 67, 74, 87, 95, 100, 107,
               115, 124, 131, 139, 146, 153, 158, 167, 177, 186, 194, 203]

PAUSE_MS     = 50           # silence to insert after each chosen word
VOICE        = 'af_heart'   # see README language/voice table
LANG_CODE    = 'a'          # 'a' = American English
SPEED        = 1.0
CROSSFADE_MS = 5.0          # click-free blend; keep < PAUSE_MS
PROBE        = True         # verify index->word against the model's real output before generating
OUT_WAV      = 'ios27_pauses.wav'

# Numbers must be letters or MMS_FA drops the token and shifts every later index.
# \\b27\\b matches '27' and the 27 inside \"27's\", apostrophe style irrelevant.
NUMBER_FIXES = {r'\b27\b': 'twenty-seven'}

import re, io, base64, unicodedata, requests

def clean_word(w):
    """Mirror of the server's _clean_word (Latin branch): strip punctuation, fold accents."""
    c = re.sub(r'[^\w\s]', '', w, flags=re.UNICODE).strip()
    if not c:
        return ''
    n = unicodedata.normalize('NFD', c)
    return ''.join(ch for ch in n if unicodedata.category(ch) != 'Mn')

def normalize_numbers(text, fixes):
    for pat, repl in fixes.items():
        text = re.sub(pat, repl, text)
    return text

def pre_align_wordlist(text):
    """The word order/index space pause_after uses, assuming every word aligns."""
    return [w for w in text.split() if clean_word(w)]

def runpod_runsync(payload, timeout=600):
    url = f'https://api.runpod.ai/v2/{KOKORO_ENDPOINT_ID}/runsync'
    headers = {'Authorization': f'Bearer {RUNPOD_API_KEY}', 'Content-Type': 'application/json'}
    r = requests.post(url, json={'input': payload}, headers=headers, timeout=timeout)
    r.raise_for_status()
    body = r.json()
    out = body.get('output', body)
    if isinstance(out, dict) and out.get('error'):
        raise RuntimeError(out['error'])
    return out

# Normalize, then sanity-check the requested indices.
TEXT_N = normalize_numbers(TEXT, NUMBER_FIXES)
local_words = pre_align_wordlist(TEXT_N)
print(f'local word count: {len(local_words)}  (valid indices 0..{len(local_words)-2})')

valid   = [i for i in PAUSE_AFTER if 0 <= i < len(local_words) - 1]
dropped = [i for i in PAUSE_AFTER if i not in valid]
if dropped:
    print('out of range, will be ignored:', dropped)

ref = local_words
if PROBE:
    probe = runpod_runsync({'text': TEXT_N, 'voice': VOICE, 'lang_code': LANG_CODE,
                            'speed': SPEED, 'timestamps': True})
    server_words = [wt['word'] for wt in probe.get('word_timestamps', [])]
    print(f'server aligned word count: {len(server_words)}')
    if len(server_words) != len(local_words):
        print('WARNING: counts differ -> the aligner dropped/added tokens; '
              'indices below come from the SERVER list and are authoritative.')
    ref = server_words
    valid = [i for i in PAUSE_AFTER if 0 <= i < len(ref) - 1]

print('\nindex -> word the 50 ms lands AFTER:')
for i in valid:
    print(f'  {i:>3}: {ref[i]!r}')

# Generate: synth + 50 ms pauses + offset-corrected timestamps.
out = runpod_runsync({
    'text': TEXT_N, 'voice': VOICE, 'lang_code': LANG_CODE, 'speed': SPEED,
    'timestamps': True, 'word_boundaries': True,
    'pause_after': valid, 'micro_pause_ms': PAUSE_MS, 'crossfade_ms': CROSSFADE_MS,
})

audio = base64.b64decode(out['audio_base64'])
with open(OUT_WAV, 'wb') as f:
    f.write(audio)

print(f"duration: {out['duration_seconds']}s   sample_rate: {out['sample_rate']}   "
      f"pauses inserted: {len(valid)}")

import IPython.display as ipd
