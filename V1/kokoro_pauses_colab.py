# Word timestamps (already shifted for the inserted pauses).
ts = out.get('word_timestamps', [])
print(f'{len(ts)} words\n')
for k, wt in enumerate(ts):
    gap = ''
    if k + 1 < len(ts):
        g = (ts[k+1]['start'] - wt['end']) * 1000
        gap = f'  gap->next {g:5.0f} ms'
    print(f"{k:>3}  {wt['word']:<16} {wt['start']:>7.3f} - {wt['end']:>7.3f}{gap}")

